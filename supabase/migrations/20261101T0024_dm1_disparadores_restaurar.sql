CREATE OR REPLACE FUNCTION public.trg_propose_vat_on_family()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
  v_family_name text;
  v_cat         uuid;
BEGIN
  -- DM1 · 2b-1: mientras se restaura una demo, nada (la foto ya lo trae hecho).
  if public._restaurando_demo() then return coalesce(new, old); end if;
  -- Solo actuar si hay familia y el IVA no está confirmado por un humano.
  IF NEW.family_id IS NULL THEN
    RETURN NEW;
  END IF;
  IF NEW.vat_category_source = 'confirmed' THEN
    RETURN NEW;
  END IF;

  -- En UPDATE: solo si la familia cambió (evita trabajo y recursión).
  IF TG_OP = 'UPDATE' AND NEW.family_id IS NOT DISTINCT FROM OLD.family_id THEN
    RETURN NEW;
  END IF;

  SELECT rf.name INTO v_family_name
  FROM public.recipe_family rf WHERE rf.id = NEW.family_id;

  IF v_family_name IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT fvd.vat_category_id INTO v_cat
  FROM public.family_vat_default fvd
  WHERE fvd.family_name = v_family_name;

  IF v_cat IS NULL THEN
    RETURN NEW;  -- familia sin mapeo fiscal → no inventa, deja como está
  END IF;

  -- Escribir directamente en NEW (BEFORE trigger) → sin re-disparo ni recursión.
  NEW.vat_category_id := v_cat;
  NEW.vat_category_source := 'proposed';
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.trg_sale_push_status()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_pushable text[] := array[
    'in_preparation','awaiting_collection','awaiting_shipment',
    'in_delivery','completed','rejected','cancelled','delivery_failed'
  ];
  v_secret text;
begin
  -- DM1 · 2b-1: mientras se restaura una demo, nada (la foto ya lo trae hecho).
  if public._restaurando_demo() then return coalesce(new, old); end if;
  -- solo canales con empuje y estados empujables
  if new.source = 'lastapp' and new.order_status = any(v_pushable) then
    -- W10a: el secreto, del Vault (order_advance_secret); ya no va escrito.
    -- Si falta, no se llama a nadie y queda dicho; el pedido sigue.
    select decrypted_secret into v_secret from vault.decrypted_secrets where name = 'order_advance_secret';
    if v_secret is null then
      begin
        perform public._queue_system_alert(
          'vault',
          'Sin llamar a order-advance: falta order_advance_secret en el Vault',
          format('El pedido %s (estado %s) no ha avisado a order-advance porque el Vault de este proyecto no tiene order_advance_secret. El pedido se ha guardado; el aviso a la plataforma no ha salido.', new.id, new.order_status),
          'vault-order-advance');
      exception when others then
        raise warning 'trg_sale_push_status: falta order_advance_secret y no se pudo avisar (venta %): %', new.id, sqlerrm;
      end;
      return new;
    end if;
    perform net.http_post(
      url     := 'https://xzmpnchlguibclvxyynt.supabase.co/functions/v1/order-advance',
      headers := jsonb_build_object(
        'Content-Type',            'application/json',
        'x-order-advance-secret',  v_secret
      ),
      body    := jsonb_build_object(
        'sale_id',    new.id,
        'new_status', new.order_status,
        'internal',   true
      )
    );
  end if;
  return new;
end;
$function$;

