        VALUES (new.id, new.account_id, new.location_id, 'offered', 'auto');
      END IF;

    ELSIF v_carrier = 'catcher' THEN
      SELECT decrypted_secret INTO v_secret
        FROM vault.decrypted_secrets WHERE name = 'catcher_dispatch_secret';
