           AND (c.assigned_locations = '{}'::uuid[] OR new.location_id = ANY(c.assigned_locations))
         ORDER BY (CASE WHEN c.last_lat IS NOT NULL AND c.last_lng IS NOT NULL AND l.lat IS NOT NULL AND l.lng IS NOT NULL
